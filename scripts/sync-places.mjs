import {LANDMARKS} from '../web/src/game/landmarks/index.js'
import {project,isWater} from '../web/src/game/geo.js'
import {writeFile,readFile} from 'node:fs/promises'
const ids=new Set()
const places=LANDMARKS.map(def=>{
 if(ids.has(def.id))throw Error('Duplicate landmark: '+def.id);ids.add(def.id)
 const p=project(def.lat,def.lon);let {x,z}=p
 if(def.snap){const [dx,dz]={south:[0,1],north:[0,-1],east:[1,0],west:[-1,0]}[def.snap];for(let i=0;i<1500;i++){if(isWater(x+dx*i,z+dz*i)){const k=i-(def.snapOff||0);x+=dx*k;z+=dz*k;break}}}
 return {id:def.id,name:def.name,lat:def.lat,lon:def.lon,x,z,radius:def.photoR||380}
})
const content='// Generated by scripts/sync-places.mjs from the canonical procedural registry.\nexport const LANDMARKS = '+JSON.stringify(places,null,2)+'\n'
const target=new URL('../server/src/places.ts',import.meta.url)
if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==content)throw Error('Server place registry is stale. Run npm run sync:places')}else await writeFile(target,content)
console.log('Place registry synchronized:',places.length,'unique landmarks')
